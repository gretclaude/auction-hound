/**
 * Generate HTML for a single item
 */
function generateItemHTML(match, isHighConfidence) {
  const { newItem, matchedFavorite, similarity } = match;

  const imageUrl = newItem.images?.[0] || '';
  const title = newItem.title || 'Untitled';
  const url = newItem.url || '#';
  const endTime = newItem.endTime || 'N/A';
  const currentBid = newItem.currentBid || 'N/A';
  const estimate = newItem.estimate || 'N/A';

  return `
    <div class="item ${isHighConfidence ? 'high-confidence' : ''}">
      <img src="${imageUrl}" alt="${title}">
      <div class="item-details">
        <span class="similarity">${similarity}% Match</span>
        <div class="item-title">
          <a href="${url}" target="_blank">${title}</a>
        </div>
        <div class="item-meta">⏰ Ends: ${endTime}</div>
        <div class="item-meta">💰 Current bid: ${currentBid}</div>
        ${estimate ? `<div class="item-meta">📊 Estimate: ${estimate}</div>` : ''}
        <div class="matched-to">
          <strong>Matched to your favorite:</strong><br>
          ${matchedFavorite.title || matchedFavorite.itemId}
        </div>
      </div>
    </div>
  `;
}

/**
 * Generate plain text version
 */
export function generateEmailText(matches, threshold) {
  let text = `🔔 NEW SIMILAR AUCTIONS FOUND!\n\n`;
  text += `Found ${matches.length} similar item${matches.length !== 1 ? 's' : ''}\n`;
  text += `Threshold: ${threshold}%\n\n`;
  text += `${'='.repeat(60)}\n\n`;

  const highConfidence = matches.filter(m => m.similarity >= 85);
  const mediumConfidence = matches.filter(m => m.similarity >= threshold && m.similarity < 85);

  if (highConfidence.length > 0) {
    text += `✨ HIGH CONFIDENCE MATCHES\n\n`;
    highConfidence.forEach((match, i) => {
      text += formatMatchText(match, i + 1);
    });
  }

  if (mediumConfidence.length > 0) {
    text += `\n🔍 MAYBE CHECK THESE TOO\n\n`;
    mediumConfidence.forEach((match, i) => {
      text += formatMatchText(match, i + 1);
    });
  }

  text += `\n${'='.repeat(60)}\n`;
  text += `\nThis alert was generated by Auction Hound 🐕\n`;

  return text;
}

/**
 * Format a single match for text email
 */
function formatMatchText(match, index) {
  const { newItem, matchedFavorite, similarity } = match;

  let text = `${index}. ${newItem.title || 'Untitled'}\n`;
  text += `   Similarity: ${similarity}%\n`;
  text += `   Link: ${newItem.url}\n`;
  text += `   Ends: ${newItem.endTime || 'N/A'}\n`;
  text += `   Current bid: ${newItem.currentBid || 'N/A'}\n`;
  if (newItem.estimate) {
    text += `   Estimate: ${newItem.estimate}\n`;
  }
  text += `   Matched to: ${matchedFavorite.title || matchedFavorite.itemId}\n`;
  text += `\n`;

  return text;
}

/**
 * Send email notification
 */
export async function sendMatchEmail(transporter, toEmail, matches, threshold) {
  const htmlContent = generateEmailHTML(matches, threshold);
  const textContent = generateEmailText(matches, threshold);

  const mailOptions = {
    from: transporter.options.auth.user,
    to: toEmail,
    subject: `🔔 Found ${matches.length} Similar Auction${matches.length !== 1 ? 's' : ''}!`,
    text: textContent,
    html: htmlContent
  };

  try {
    const info = await transporter.sendMail(mailOptions);
    console.log('✅ Email sent:', info.messageId);
    return info;
  } catch (error) {
    throw new Error(`Failed to send email: ${error.message}`);
  }
}

/**
 * Save email HTML to file (for testing without sending)
 */
export async function saveEmailPreview(matches, threshold) {
  const htmlContent = generateEmailHTML(matches, threshold);
  const previewPath = './data/email-preview.html';

  await fs.mkdir('./data', { recursive: true });
  await fs.writeFile(previewPath, htmlContent);

  console.log(`📧 Email preview saved to: ${previewPath}`);
  return previewPath;
}
