/**
 * Email notification system
 * Sends HTML emails with image thumbnails and links
 */

/**
 * Create email transporter (MSN/Outlook)
 */
export function createTransporter(emailUser, emailPassword) {
  return nodemailer.createTransporter({
    host: 'smtp-mail.outlook.com',
    port: 587,
    secure: false,
    auth: {
      user: emailUser,
      pass: emailPassword
    }
  });
}

